# auto-tracked toddler shots: smooth + inflate radius
def auto(path):
    d=json.load(open(path))['data']; d=[k for k in d if k[1] is not None]
    a=np.array(d); out=[]
    for i in range(len(a)):
        lo,hi=max(0,i-3),min(len(a),i+4)
        x=np.median(a[lo:hi,1]); y=np.median(a[lo:hi,2]); r=np.max(a[max(0,i-6):i+7,3])
        out.append([float(a[i,0]),float(x),float(y),float(r)])
    return {'type':'kf','data':out}
